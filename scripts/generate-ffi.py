"""Generate fixed ABI 2 structure declarations from the public C source of truth."""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
source = (ROOT / "include/maa-capture/CaptureTypes.h").read_text(encoding="utf-8")
structs = []
for body, name in re.findall(r"typedef struct \w+_\s*\{(.*?)\}\s*(\w+);", source, re.S):
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    fields = []
    for declaration in body.split(";"):
        declaration = declaration.strip()
        if not declaration:
            continue
        kind, names = re.match(r"(const uint8_t\*|\w+)\s+(.+)", declaration).groups()
        for item in names.split(","):
            field, count = re.fullmatch(r"(\w+)(?:\[(\w+)\])?", item.strip()).groups()
            if count == "MAA_WS_KEY_CAPACITY":
                count = "512"
            fields.append((field, kind, int(count) if count else None))
    structs.append((name, fields))

banner = "// Generated by scripts/generate-ffi.py. Do not edit.\n"
py = "# Generated by scripts/generate-ffi.py. Do not edit.\nimport ctypes as C\n"
cs = banner + "using System;\nusing System.Runtime.InteropServices;\nnamespace MaaCapture {\n"
rs = banner + "use std::ffi::c_void;\n"
node = banner + "'use strict';\nconst koffi = require('koffi');\n"
java = banner + "package maa.capture;\nimport com.sun.jna.*;\npublic class NativeTypes {\n"
go = "//go:build windows && amd64\n\n" + banner + "package maa_capture\n\n"
maps = {
    "py": {"uint32_t":"C.c_uint32","int32_t":"C.c_int32","uint64_t":"C.c_uint64","int64_t":"C.c_int64","double":"C.c_double","char":"C.c_char","const uint8_t*":"C.c_void_p"},
    "cs": {"uint32_t":"uint","int32_t":"int","uint64_t":"ulong","int64_t":"long","double":"double","char":"byte","const uint8_t*":"IntPtr"},
    "rs": {"uint32_t":"u32","int32_t":"i32","uint64_t":"u64","int64_t":"i64","double":"f64","char":"u8","const uint8_t*":"*const c_void"},
    "node": {"uint32_t":"'uint32'","int32_t":"'int32'","uint64_t":"'uint64'","int64_t":"'int64'","double":"'double'","char":"'char'","const uint8_t*":"'void *'"},
    "java": {"uint32_t":"int","int32_t":"int","uint64_t":"long","int64_t":"long","double":"double","char":"byte","const uint8_t*":"Pointer"},
    "go": {"uint32_t":"uint32","int32_t":"int32","uint64_t":"uint64","int64_t":"int64","double":"float64","char":"byte","const uint8_t*":"uintptr"},
}
for name, fields in structs:
    py += f"class {name}(C.Structure):\n    _fields_ = [\n"
    cs += f"[StructLayout(LayoutKind.Sequential)] public struct {name} {{\n"
    rs += f"#[repr(C)]\n#[derive(Clone, Copy)]\npub struct {name} {{\n"
    node += f"const {name} = koffi.struct('{name}', {{\n"
    java += '@Structure.FieldOrder({' + ",".join('"'+f+'"' for f,_,_ in fields) + '})\n'
    java += f"public static class {name} extends Structure {{\n"
    go += f"type {name} struct {{\n"
    for field, kind, count in fields:
        types = {lang: m.get(kind,kind) for lang,m in maps.items()}
        py += f"        ('{field}', {types['py']}" + (f" * {count}" if count else "") + "),\n"
        cs += (f"[MarshalAs(UnmanagedType.ByValArray, SizeConst={count})] public {types['cs']}[] {field};\n" if count else f"public {types['cs']} {field};\n")
        rs += f"pub {field if field != 'type' else 'type_'}: " + (f"[{types['rs']}; {count}]" if count else types["rs"]) + ",\n"
        node += f"{field}: " + (f"koffi.array({types['node']}, {count})" if count else types["node"]) + ",\n"
        java += (f"public {types['java']}[] {field} = new {types['java']}[{count}];\n" if count else f"public {types['java']} {field}" + (f" = new {kind}()" if kind.startswith("MaaWS") else "") + ";\n")
        go += field[:1].upper()+field[1:] + " " + (f"[{count}]" if count else "") + types["go"] + "\n"
    py += "    ]\n"
    cs += "}\n"; rs += "}\n"; node += "});\n"; go += "}\n"
    java += f"public {name}() {{ super(); }}\npublic {name}(Pointer p) {{ super(p); read(); }}\n}}\n"
cs += "}\n"; java += "}\n"
node += "module.exports = {" + ",".join(name for name,_ in structs) + "};\n"
for path, text in {
    "bindings/python/src/maa_capture/_ffi.py":py,
    "bindings/csharp/NativeTypes.cs":cs,
    "bindings/rust/src/types.rs":rs,
    "bindings/nodejs/types.js":node,
    "bindings/java/NativeTypes.java":java,
    "bindings/golang/types.go":go,
}.items():
    if "--check" in sys.argv:
        if (ROOT/path).read_text(encoding="utf-8") != text:
            raise RuntimeError(f"Generated ABI declaration is stale: {path}")
    else:
        (ROOT/path).write_text(text, encoding="utf-8")
